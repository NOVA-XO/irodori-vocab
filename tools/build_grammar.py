# ── Үүсгэлтэд хэрэглэх үгийн шүүлтүүр ────────────────────────────────
#   ref=True нь «лавлах үгсийн сан» (саарал) — дасгалд оруулахгүй.


def words(voc, lesson, **kw):
    """Тухайн хичээлийн үндсэн үгс. `pred` нь нэмэлт шүүлтүүр."""
    pred = kw.get("pred")
    out = []
    for it in voc:
        if it["lesson"] != lesson or it.get("ref"):
            continue
        if not it["kana"] or not (it["mn"] or "").strip():
            continue
        # Хоёр хэлбэртэй (「〜する／〜します」) ба тэмдэгттэй мөрийг алгасна
        if u"／" in it["jp"] or u"～" in it["jp"] or u"（" in it["jp"]:
            continue
        if it["jp"].endswith((u"。", u"？", u"！")):
            continue
        if pred and not pred(it):
            continue
        out.append(it)
    return out


ASK = set(u"""なに なん どこ だれ いつ いくら どちら どう どんな いくつ
なんじ なんさい なんようび なんがつ なんにち なんばんせん なんかい""".split())
ASK_MN = set(u"юу хаана хэн хэзээ ямар яаж хэдэн хэдтэй".split())


def noun(it):
    """Нэр үг мөн үү — бүдүүвч шалгуур: үйл үгийн төгсгөлгүй, богино."""
    k = it["kana"]
    if k in ASK or (it["mn"] or "").strip().lower() in ASK_MN:
        return False                       # асуух үг — дасгалд утгагүй
    if k.endswith((u"る", u"す", u"く", u"ぐ", u"む", u"ぬ", u"ぶ", u"つ", u"う")):
        return False                       # үйл үг байж магадгүй
    if k.endswith((u"い", u"な")) and len(k) > 2:
        return False                       # тэмдэг нэр байж магадгүй
    # Бүтэн хэллэг, эелдэг хэлбэрийг НЭР ҮГ гэж авахгүй
    # («いらっしゃいませ = Тавтай морил.» гэж дасгалд орж байв).
    m = (it["mn"] or "").strip()
    if any(c in m for c in u".(!?…"):
        return False
    if k.endswith((u"ます", u"ませ", u"ください", u"です", u"ました")):
        return False
    return 2 <= len(k) <= 8


class Drill(object):
    """Нэг дасгал: 4 сонголт, эхнийх нь ЗӨВ (дараа нь холино)."""

    def __init__(self, jp, kana, mn, right, wrong):
        self.jp, self.kana, self.mn = jp, kana, mn
        self.right, self.wrong = right, list(wrong)


def D(jp, kana, mn, right, *wrong):
    return Drill(jp, kana, mn, right, wrong)


# ── Монгол нөхцөл: эгшгийн зохицол ───────────────────────────────────
#   Үүсгэсэн дасгалын тайлбар «Би Филиппин-аас ирсэн» гэж тасархай
#   гарч байв. Гарлын (-аас) ба өгөх оршихын (-д) нөхцөлийг үгийн
#   СҮҮЛИЙН ЭГШГЭЭР сонгоно.
BACK_A = u"ая"
BACK_O = u"оуё"
EXTRA_V = u"юы"
FRONT_E = u"эеи"
FRONT_O = u"өү"
VOWELS = BACK_A + BACK_O + FRONT_E + FRONT_O + EXTRA_V


def _last_vowel(w):
    for ch in reversed(w.lower()):
        if ch in VOWELS:
            return ch
    return u"а"


def abl(w):
    """Гарлын нөхцөл: Мьянмар -> Мьянмараас, Токио -> Токиогоос."""
    v = _last_vowel(w)
    suf = (u"аас" if v in BACK_A else u"оос" if v in BACK_O
           else u"ээс" if v in FRONT_E else u"өөс")
    return w + (u"г" + suf if w[-1:].lower() in VOWELS else suf)


def dat(w):
    """Өгөх оршихын нөхцөл: Токио -> Токиод, Солонгос -> Солонгост."""
    last = w[-1:].lower()
    if last in VOWELS or last in u"лмнрв":
        return w + u"д"
    return w + u"т"


def is_place(it):
    """Оноосон нэр мөн үү — өгүүлбэр, тайлбарыг гаргана.

    «Тийм ээ, зөв.» гэх мэт БҮТЭН өгүүлбэр монголоор том үсгээр эхэлдэг
    тул зөвхөн том үсгээр шалгавал утгагүй дасгал үүснэ (шалгахад
    «Би За байз…-д амьдардаг» гэж гарав).
    """
    m = (it["mn"] or "").strip()
    if not m or not m[:1].isupper():
        return False
    if any(c in m for c in u".,()/?!…"):
        return False
    if len(m.split()) > 2 or len(m) > 18:
        return False
    return len(it["kana"]) <= 8


def _fill(frame, m):
    """{m} — энгийн, {abl} — гарлын, {dat} — өгөх оршихын хэлбэр."""
    return (frame.replace(u"{abl}", abl(m)).replace(u"{dat}", dat(m))
                 .replace(u"{m}", m))


def slots(voc, lessons, frame_jp, frame_kana, frame_mn, n, pred=None, seed=0):
    """Загварын нүдийг ТУХАЙН ХИЧЭЭЛИЙН үгээр дүүргэж n дасгал үүсгэнэ.

    Хариулт нь дасгал бүрт ӨӨР үг байна (сандруулагч нь ижил хичээлээс),
    тиймээс «бүгд нэг хариулттай» гэсэн уйтгартай эгнээ гарахгүй.
    """
    if isinstance(lessons, int):
        lessons = [lessons]
    ws = []
    for L in lessons:
        ws += words(voc, L, pred=pred or noun)
    rnd = random.Random(1000 + lessons[0] * 7 + seed)
    uniq, seen_k = [], set()
    for w in ws:
        if w["kana"] not in seen_k:
            seen_k.add(w["kana"]); uniq.append(w)
    ws = uniq
    rnd.shuffle(ws)
    out = []
    for i, w in enumerate(ws):
        if len(out) >= n:
            break
        others = [x for x in ws if x["kana"] != w["kana"]]
        if len(others) < 3:
            break
        wrong = rnd.sample(others, 3)
        out.append(Drill(
            frame_jp.replace(u"{w}", BLANK),
            frame_kana.replace(u"{w}", BLANK),
            _fill(frame_mn, w["mn"].split(u"/")[0].strip()),
            w["kana"], [x["kana"] for x in wrong]))
    return out


