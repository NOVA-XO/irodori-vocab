def main():
    voc = json.load(io.open(os.path.join(ROOT, "data", "vocab.json"),
                            encoding="utf-8"))["items"]
    errs, out = [], []
    for p in POINTS:
        ds = list(p["hand"])
        if p["gen"]:
            fj, fk, fm, n, pred = p["gen"][:5]
            src = p["gen"][5] if len(p["gen"]) > 5 else p["lesson"]
            ds += slots(voc, src, fj, fk, fm, n, pred)
        if len(ds) != 20:
            errs.append("%s: дасгал %d (20 байх ёстой)" % (p["id"], len(ds)))
        seen = set()
        items = []
        for i, d in enumerate(ds, 1):
            if u"＿" not in d.jp:
                errs.append("%s-%02d: ＿＿ алга -> %s" % (p["id"], i, d.jp))
            if KANJI.search(d.kana):
                errs.append("%s-%02d: кана талбарт ХАНЗ -> %s" % (p["id"], i, d.kana))
            opts = [d.right] + d.wrong
            if len(set(opts)) != 4:
                errs.append("%s-%02d: сонголт давхардав -> %s" % (p["id"], i, opts))
            # Давхардлыг өгүүлбэр+ХАРИУЛТААР шалгана: үүсгэсэн дасгалууд
            # нэг загвартай ч хариулт нь өөр өөр байдаг.
            if (d.jp, d.right) in seen:
                errs.append("%s-%02d: дасгал давхардав -> %s" % (p["id"], i, d.jp))
            seen.add((d.jp, d.right))
            rnd = random.Random(hash(p["id"] + d.jp) & 0xffff)
            order = opts[:]
            rnd.shuffle(order)
            items.append({"id": "%s-%02d" % (p["id"], i),
                          "jp": d.jp, "kana": d.kana, "mn": d.mn,
                          "opts": order, "a": order.index(d.right)})
        for f in ("id", "lesson", "title", "form", "mn", "ex"):
            if not p.get(f):
                errs.append("%s: %s хоосон" % (p["id"], f))
        if len(p["ex"]) < 3:
            errs.append("%s: жишээ 3-аас цөөн" % p["id"])
        for e in p["ex"]:
            if KANJI.search(e[1]):
                errs.append("%s: жишээний канад ХАНЗ -> %s" % (p["id"], e[1]))
        out.append({"id": p["id"], "lesson": p["lesson"], "title": p["title"],
                    "form": p["form"], "mn": p["mn"].strip(),
                    "ex": [{"jp": a, "kana": b, "mn": c} for a, b, c in p["ex"]],
                    "drills": items})

    if errs:
        sys.stderr.write("\n".join(errs).encode("utf-8", "replace")
                         .decode("ascii", "replace") + "\n")
        raise SystemExit("ШАЛГАЛТ УНАВ: %d алдаа" % len(errs))

    doc = {"book": "starter", "title": u"Irodori 入門 — дүрмийн дасгал",
           "note": u"Дүрэм тус бүрт тайлбар, 3 жишээ, 20 дасгал. "
                   u"Дасгал нь 4 сонголттой тул автоматаар дүгнэгдэнэ.",
           "count": len(out), "drills": sum(len(p["drills"]) for p in out),
           "items": out}
    io.open(os.path.join(ROOT, "data", "grammar-starter.json"), "w",
            encoding="utf-8").write(json.dumps(doc, ensure_ascii=False,
                                               separators=(",", ":")))
    print("дүрэм: %d · дасгал: %d" % (doc["count"], doc["drills"]))
    for p in out:
        print("  %s L%-2d %-22s %d дасгал" % (p["id"], p["lesson"],
                                              p["title"], len(p["drills"])))


if __name__ == "__main__":
    main()
