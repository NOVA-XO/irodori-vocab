def main():
    errs = []
    out = []
    per_lesson = collections.Counter()
    seen = set()
    kanji = re.compile(u"[㐀-鿿]")

    for rec in Q:
        lesson, topic, qq, qkana, qmn, model, mkana, modelmn, key = rec
        if not (1 <= lesson <= 18):
            errs.append("хичээл %r буруу" % lesson)
        per_lesson[lesson] += 1
        qid = "%s%02d-%02d" % (PREFIX, lesson, per_lesson[lesson])
        if qid in seen:
            errs.append("%s: id давхардав" % qid)
        seen.add(qid)
        for name, val in (("q", qq), ("qKana", qkana), ("qMn", qmn),
                          ("model", model), ("modelKana", mkana),
                          ("modelMn", modelmn), ("topic", topic), ("key", key)):
            if not (val or "").strip():
                errs.append("%s: %s хоосон" % (qid, name))
        # КАНА талбарт ханз үлдсэн бол орхигдсон гэсэн үг — шууд барина.
        for name, val in (("qKana", qkana), ("modelKana", mkana)):
            if kanji.search(val or ""):
                errs.append("%s: %s-д ХАНЗ үлдсэн -> %s" % (qid, name, val))
        # ふりがな — уналт эсвэл эргэлзээ гарвал build зогсоно.
        rub = {}
        for fld, surf, read in (("qRuby", qq, qkana),
                                ("modelRuby", model, mkana)):
            sols = ruby_pairs(surf, read)
            if not sols:
                errs.append("%s: %s зэрэгцүүлж чадсангүй -> %s / %s"
                            % (qid, fld, surf, read))
                continue
            if len(sols) > 1:
                errs.append("%s: %s ЭРГЭЛЗЭЭТЭЙ (%d хувилбар) -> %s"
                            % (qid, fld, len(sols), surf))
                continue
            p = sols[0]
            if "".join(t for t, _ in p) != surf:
                errs.append("%s: %s ханзан хэлбэр сэргэхгүй" % (qid, fld))
            if "".join(r or t for t, r in p) != read:
                errs.append("%s: %s канан хэлбэр сэргэхгүй" % (qid, fld))
            rub[fld] = p

        free = 0 if (FIXED_MARK.search(qq) and qq not in FREE_ANYWAY) else 1
        item = {
            "id": qid, "lesson": lesson, "topic": topic,
            "q": qq, "qKana": qkana, "qMn": qmn,
            "model": model, "modelKana": mkana, "modelMn": modelmn, "key": key,
            "free": free,
        }
        item.update(rub)
        out.append(item)

    # Сан бүрэн болсон — тоо ЯГ таарч байх ёстой. Асуулт санамсаргүй
    # хасагдвал эсвэл давхардвал энд баригдана.
    if len(Q) != TOTAL:
        errs.append("Нийт асуулт %d (%d байх ёстой)" % (len(Q), TOTAL))
    for l in range(1, 19):
        n = sum(1 for r in Q if r[0] == l)
        if n != 10:
            errs.append("L%d: %d асуулт (10 байх ёстой)" % (l, n))

    if errs:
        # Алдааны БҮТЭН текстийг UTF-8 файлд бичнэ. Консол руу шууд
        # бичвэл кирилл/япон нь cp1252-д `?` болж, аль асуулт эвдэрсэн
        # нь харагдахаа больдог (docs/STATE.md §2.1).
        log = os.path.join(HERE, "_exam_el1_errors.txt")
        with io.open(log, "w", encoding="utf-8", newline="") as f:
            f.write("\n".join(errs) + "\n")
        sys.stderr.write("BUILD FAILED: %d errors -> %s\n" % (len(errs), log))
        raise SystemExit(1)

    doc = {
        "book": BOOK,
        "title": "Irodori 初級1 — харилцааны шалгалт",
        "kind": "self",
        "note": "Сурагч асуултад хариулаад, загвар хариултыг харж өөрөө "
                "«чадсан/чадаагүй» гэж тэмдэглэнэ. Ханз/кана сонголттой. "
                "Багш tools/build_exam_el1.py-д асуулт нэмж/заснаа дахин ажиллуулна.",
        "version": 1,
        "count": len(out),
        "items": out,
    }
    dst = os.path.join(ROOT, "data", "exam-el1.json")
    with io.open(dst, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")

    nr = sum(1 for it in out if it.get("qRuby"))
    nf = sum(it["free"] for it in out)
    print("OK  exam-el1.json  questions=%d/%d  ruby=%d  free=%d  fixed=%d"
          % (len(out), TOTAL, nr, nf, len(out) - nf))
    print("per lesson:", " ".join("L%d=%d" % (l, per_lesson[l])
                                  for l in sorted(per_lesson)))


if __name__ == "__main__":
    main()
