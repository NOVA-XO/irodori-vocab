def main():
    errs = []
    out = []
    per_lesson = collections.Counter()
    seen = set()
    kanji = re.compile(u"[㐀-鿿]")

    for rec in Q:
        lesson, topic, qq, qkana, qmn, model, mkana, modelmn, key = rec
        if not (1 <= lesson <= 18):
            errs.append("хичээл %r буруу" % lesson)
        per_lesson[lesson] += 1
        qid = "S%02d-%02d" % (lesson, per_lesson[lesson])
        if qid in seen:
            errs.append("%s: id давхардав" % qid)
        seen.add(qid)
        for name, val in (("q", qq), ("qKana", qkana), ("qMn", qmn),
                          ("model", model), ("modelKana", mkana),
                          ("modelMn", modelmn), ("topic", topic), ("key", key)):
            if not (val or "").strip():
                errs.append("%s: %s хоосон" % (qid, name))
        # КАНА талбарт ханз үлдсэн бол орхигдсон гэсэн үг — шууд барина.
        for name, val in (("qKana", qkana), ("modelKana", mkana)):
            if kanji.search(val or ""):
                errs.append("%s: %s-д ХАНЗ үлдсэн -> %s" % (qid, name, val))
        out.append({
            "id": qid, "lesson": lesson, "topic": topic,
            "q": qq, "qKana": qkana, "qMn": qmn,
            "model": model, "modelKana": mkana, "modelMn": modelmn, "key": key,
        })

    if len(Q) != 100:
        errs.append("Нийт асуулт %d (100 байх ёстой)" % len(Q))

    if errs:
        sys.stderr.write("\n".join(errs).encode("utf-8", "replace")
                         .decode("ascii", "replace") + "\n")
        raise SystemExit("ШАЛГАЛТ УНАВ: %d алдаа" % len(errs))

    doc = {
        "book": "starter",
        "title": "Irodori 入門 — харилцааны шалгалт",
        "kind": "self",     # өөрөө үнэлэх (аман шалгалт шиг)
        "note": "Сурагч асуултад хариулаад, загвар хариултыг харж өөрөө "
                "«чадсан/чадаагүй» гэж тэмдэглэнэ. Ханз/кана сонголттой. "
                "Багш tools/build_exam.py-д асуулт нэмж/заснаа дахин ажиллуулна.",
        "version": 3,
        "count": len(out),
        "items": out,
    }
    dst = os.path.join(ROOT, "data", "exam-starter.json")
    with io.open(dst, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")

