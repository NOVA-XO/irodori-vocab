def main():
    errs = []
    out = []
    per_lesson = collections.Counter()
    seen = set()

    for lesson, topic, q, qmn, model, modelmn, key in Q:
        if not (1 <= lesson <= 18):
            errs.append("хичээл %r буруу" % lesson)
        per_lesson[lesson] += 1
        qid = "S%02d-%02d" % (lesson, per_lesson[lesson])
        if qid in seen:
            errs.append("%s: id давхардав" % qid)
        seen.add(qid)
        for name, val in (("q", q), ("qMn", qmn), ("model", model),
                          ("modelMn", modelmn), ("topic", topic), ("key", key)):
            if not (val or "").strip():
                errs.append("%s: %s хоосон" % (qid, name))
        out.append({
            "id": qid, "lesson": lesson, "topic": topic,
            "q": q, "qMn": qmn, "model": model, "modelMn": modelmn, "key": key,
        })

    if len(Q) != 100:
        errs.append("Нийт асуулт %d (100 байх ёстой)" % len(Q))

    if errs:
        sys.stderr.write("\n".join(errs).encode("utf-8", "replace")
                         .decode("ascii", "replace") + "\n")
        raise SystemExit("ШАЛГАЛТ УНАВ: %d алдаа" % len(errs))

    # ── Мэдээллийн шалгалт: асуултад ашигласан үг номд байгаа эсэх ──
    # Унагахгүй — зөвхөн багшид харуулна. Номд байхгүй үг олон байвал
    # асуулт түвшнээсээ давсан байж магадгүй.
    src = os.path.join(ROOT, "data", "vocab.json")
    known = set()
    if os.path.exists(src):
        with io.open(src, encoding="utf-8") as f:
            d = json.load(f)
        for it in (d["items"] if isinstance(d, dict) and "items" in d else d):
            for k in ("jp", "kana"):
                v = (it.get(k) or "").strip()
                if v:
                    known.add(v)

    doc = {
        "book": "starter",
        "title": "Irodori 入門 — харилцааны шалгалт",
        "kind": "self",     # өөрөө үнэлэх (аман шалгалт шиг)
        "note": "Сурагч асуултад хариулаад, загвар хариултыг харж өөрөө "
                "«чадсан/чадаагүй» гэж тэмдэглэнэ. Багш tools/build_exam.py-д "
                "асуулт нэмж/заснаа дахин ажиллуулна.",
        "version": 2,
        "count": len(out),
        "items": out,
    }
    dst = os.path.join(ROOT, "data", "exam-starter.json")
    with io.open(dst, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")

    print("OK  exam-starter.json  questions=%d  kind=self" % len(out))
    print("per lesson:", " ".join("L%d=%d" % (l, per_lesson[l])
                                  for l in sorted(per_lesson)))


if __name__ == "__main__":
    main()
