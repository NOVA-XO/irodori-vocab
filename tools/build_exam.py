def main():
    src = os.path.join(ROOT, "data", "vocab.json")
    with io.open(src, encoding="utf-8") as f:
        d = json.load(f)
    items = d["items"] if isinstance(d, dict) and "items" in d else d

    # jp -> бичлэг (эхний тохиолдлыг авна; ижил jp давтагдвал аль нэг нь хангалттай)
    by_jp = {}
    for it in items:
        jp = (it.get("jp") or "").strip()
        if jp and jp not in by_jp:
            by_jp[jp] = it

    errs = []
    out = []
    seen_ids = set()
    per_lesson = collections.Counter()

    for n, (lesson, topic, q, ans, dis) in enumerate(Q, 1):
        qid = "S%02d-%02d" % (lesson, per_lesson[lesson] + 1)
        per_lesson[lesson] += 1
        if qid in seen_ids:
            errs.append("%s: id давхардав" % qid)
        seen_ids.add(qid)

        a_it = by_jp.get(ans)
        if not a_it:
            errs.append("%s: ХАРИУЛТ санд алга -> %r" % (qid, ans))
            continue
        if len(dis) != 3:
            errs.append("%s: сандруулагч %d ширхэг (3 байх ёстой)" % (qid, len(dis)))
        if len(set(dis)) != len(dis):
            errs.append("%s: сандруулагч давхардсан" % qid)
        if ans in dis:
            errs.append("%s: хариулт сандруулагчид орсон" % qid)

        dis_items = []
        a_mn = (a_it.get("mn") or "").strip()
        for dj in dis:
            it = by_jp.get(dj)
            if not it:
                errs.append("%s: сандруулагч санд алга -> %r" % (qid, dj))
                continue
            if (it.get("mn") or "").strip() == a_mn:
                errs.append("%s: сандруулагч %r нь хариулттай ИЖИЛ утгатай" % (qid, dj))
            dis_items.append(it)

        out.append({
            "id": qid,
            "lesson": lesson,
            "topic": topic,
            "q": q,
            "a": {"jp": ans, "kana": a_it.get("kana", ""), "mn": a_mn, "wid": a_it.get("id", "")},
            "dis": [{"jp": (x.get("jp") or ""), "kana": x.get("kana", ""),
                     "mn": (x.get("mn") or ""), "wid": x.get("id", "")} for x in dis_items],
        })

    if len(Q) != 100:
        errs.append("Нийт асуулт %d (100 байх ёстой)" % len(Q))

    if errs:
        sys.stderr.write("\n".join(errs).encode("utf-8", "replace").decode("ascii", "replace") + "\n")
        raise SystemExit("ШАЛГАЛТ УНАВ: %d алдаа" % len(errs))

    doc = {
        "book": "starter",
        "title": "Irodori 入門 — шалгалт",
        "note": "Асуултыг багш нэмж, засаж болно. Хариулт/сандруулагч нь "
                "data/vocab.json-ийн jp талбартай ЯГ таарах ёстой.",
        "version": 1,
        "count": len(out),
        "items": out,
    }
    dst = os.path.join(ROOT, "data", "exam-starter.json")
    with io.open(dst, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")

    print("OK  exam-starter.json  questions=%d" % len(out))
    print("per lesson:", " ".join("L%d=%d" % (l, per_lesson[l]) for l in sorted(per_lesson)))


if __name__ == "__main__":
    main()
